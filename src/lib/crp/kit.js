// Fallback "Asset Editor import kit": OBJ + MTL + PNG maps in a plain ZIP (stored, no compression).
// This is NOT a CRP; it is offered only so the model/textures are never locked inside a package
// that the game rejects. The kit is clearly named .zip.
import { ByteWriter } from './binary.js';

const crcTable = (() => { const t = new Uint32Array(256); for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; t[n] = c >>> 0; } return t; })();
const crc32 = (b) => { let c = 0xffffffff; for (let i = 0; i < b.length; i++) c = crcTable[(c ^ b[i]) & 255] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; };

export function zipStore(files) {
  const w = new ByteWriter(1 << 20);
  const central = [];
  const enc = new TextEncoder();
  for (const f of files) {
    const name = enc.encode(f.name);
    const crc = crc32(f.data);
    const offset = w.pos;
    w.u32(0x04034b50).u16(20).u16(0x0800).u16(0).u16(0).u16(0x21).u32(crc).u32(f.data.length).u32(f.data.length).u16(name.length).u16(0).bytes(name).bytes(f.data);
    central.push({ name, crc, size: f.data.length, offset });
  }
  const cdStart = w.pos;
  for (const c of central) {
    w.u32(0x02014b50).u16(20).u16(20).u16(0x0800).u16(0).u16(0).u16(0x21).u32(c.crc).u32(c.size).u32(c.size).u16(c.name.length).u16(0).u16(0).u16(0).u16(0).u32(0).u32(c.offset).bytes(c.name);
  }
  const cdSize = w.pos - cdStart;
  w.u32(0x06054b50).u16(0).u16(0).u16(central.length).u16(central.length).u32(cdSize).u32(cdStart).u16(0);
  return w.result();
}

export function toObj(mesh, name) {
  const lines = [`# ${name} - generated by Signboard Creator (right-handed, Y up, metres)`, `mtllib ${name}.mtl`, `o ${name}`];
  for (let i = 0; i < mesh.vertexCount; i++) lines.push(`v ${mesh.positions[i * 3].toFixed(5)} ${mesh.positions[i * 3 + 1].toFixed(5)} ${mesh.positions[i * 3 + 2].toFixed(5)}`);
  for (let i = 0; i < mesh.vertexCount; i++) lines.push(`vt ${mesh.uvs[i * 2].toFixed(5)} ${mesh.uvs[i * 2 + 1].toFixed(5)}`);
  for (let i = 0; i < mesh.vertexCount; i++) lines.push(`vn ${mesh.normals[i * 3].toFixed(4)} ${mesh.normals[i * 3 + 1].toFixed(4)} ${mesh.normals[i * 3 + 2].toFixed(4)}`);
  lines.push(`usemtl ${name}_mat`);
  for (let i = 0; i < mesh.indices.length; i += 3) {
    const a = mesh.indices[i] + 1, b = mesh.indices[i + 1] + 1, c = mesh.indices[i + 2] + 1;
    lines.push(`f ${a}/${a}/${a} ${b}/${b}/${b} ${c}/${c}/${c}`);
  }
  return new TextEncoder().encode(lines.join('\n') + '\n');
}
